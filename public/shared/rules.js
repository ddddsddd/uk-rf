export const N = ARTICLES.length;

// 1 — победила a, -1 — победила b, 0 — ничья
export function outcome(a, b) {
  const d = (b - a + N) % N;
  if (d === 0 || d === N / 2) return 0;
  return d < N / 2 ? 1 : -1;
}

export function beatsList(a) {
  return [1, 2, 3, 4].map((k) => (a + k) % N);
}
export function losesList(a) {
  return [1, 2, 3, 4].map((k) => (a - k + N) % N);
}
export function drawWith(a) {
  return (a + N / 2) % N;
}


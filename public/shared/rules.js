export function winText(w, l) {
  return WIN[`${w}-${l}`] || 'Суд вынес решение';
}

export function drawText(a, b) {
  if (a === b) return 'Подельники! Пойдёте по одной статье — группой лиц';
  const k = a < b ? `${a}-${b}` : `${b}-${a}`;
  return DRAW[k] || 'Суд не смог определиться';
}

// Проверка баланса при загрузке модуля (на случай правок таблиц)
for (let a = 0; a < N; a++) {
  for (const b of beatsList(a)) {
    if (!WIN[`${a}-${b}`]) throw new Error(`Нет подписи для победы ${a}-${b}`);
  }
}
